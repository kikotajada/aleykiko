(() => {
  const B = window.BODA;
  const $ = (s, el = document) => el.querySelector(s);
  const $$ = (s, el = document) => [...el.querySelectorAll(s)];
  const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

  let lang = "es";
  try {
    lang = localStorage.getItem("lang") || "es";
  } catch {}

  const L = (v) => (v == null ? "" : typeof v === "string" ? v : v[lang]);
  const t = (k) => B.t[lang][k] ?? k;
  const fmt = (d, o) => new Intl.DateTimeFormat(lang === "es" ? "es-ES" : "en-GB", o).format(d);
  const listJoin = (a) => (a.length < 2 ? a.join("") : a.slice(0, -1).join(", ") + (lang === "es" ? " y " : " & ") + a.at(-1));

  // An invitation is opened either by finding your name (step 1) or with a personal link ?i=KEY.
  // KEY is an opaque code generated by the Apps Script, so invitations can't be guessed.
  const params = new URLSearchParams(location.search);
  let key = params.get("i") || "";
  try {
    if (key) localStorage.setItem("rsvp_i", key);
    else key = localStorage.getItem("rsvp_i") || "";
  } catch {}

  // party: { invitation, guests:[{row,name,menu,allergies,status}], options:{plusOne,bus}, replied, bus, song, contact, message }
  let party = null;
  let partyState = key ? "loading" : "find"; // find | loading | ok | bad

  // ---------- render ----------
  function render() {
    document.documentElement.lang = lang;
    $("#lang").textContent = lang === "es" ? "EN" : "ES";
    $$("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
    $$("[data-i18n-ph]").forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));

    const [a, b] = B.names;
    $("#names").innerHTML = `${esc(a)} <em>&amp;</em> ${esc(b)}`;
    $("#names-foot").innerHTML = `${esc(a)} <em>&amp;</em> ${esc(b)}`;

    // "YYYY-MM-DD" (no time yet) is read as a local date so it never shifts a day by time zone
    const dOnly = /^\d{4}-\d{2}-\d{2}$/.test(B.date || "");
    const date = !B.date ? null : dOnly ? new Date(...B.date.split("-").map((n, i) => +n - (i === 1))) : new Date(B.date);
    $("#when").textContent = date
      ? `${fmt(date, { day: "numeric", month: "long", year: "numeric" })} · ${B.city || B.venue.town}`
      : L(B.dateText);
    const days = date ? Math.floor((date - Date.now()) / 864e5) : 0;
    $("#countdown").textContent = days > 0 ? t("countdown").replace("{n}", days) : "";

    $("#story").innerHTML = B.story
      .map(
        (s) => `<li class="reveal">
          ${s.img ? `<figure><img src="${esc(s.img)}" alt="${esc(L(s.title))}" loading="lazy" width="1200" height="900"></figure>` : ""}
          <div class="story-text"><span class="place">${esc(L(s.place))}</span><h3>${esc(L(s.title))}</h3><p>${esc(L(s.text))}</p></div>
        </li>`
      )
      .join("");

    const tbc = B.scheduleApprox || B.schedule.some((e) => !e.time);
    $("#timeline-tbc").textContent = tbc ? t("schedule_tbc") : "";
    $("#timeline-tbc").hidden = !tbc;
    $("#timeline").innerHTML = B.schedule
      .map((e) => `<li class="reveal"><time class="${e.time ? "" : "tbc"}">${e.time ? esc(e.time) : "–"}</time><div><h3>${esc(L(e.title))}</h3><p>${esc(L(e.text))}</p></div></li>`)
      .join("");

    const mapUrl = (p) => `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${L(p.name)}, ${p.address || p.town}`)}`;
    $("#cards").innerHTML = B.info
      .map((c) => {
        const place = c.map && B[c.map];
        return `<article class="card reveal"><p class="tag">${esc(L(c.tag))}</p><h3>${esc(L(c.title))}</h3>
          ${place ? `<p class="place">${esc(L(place.name))} · ${esc(place.town)}</p>` : ""}
          <p>${esc(L(c.text))}</p>
          ${place && place.confirmed !== false ? `<a class="link" href="${mapUrl(place)}" target="_blank" rel="noopener">${esc(t("open_map"))} →</a>` : ""}</article>`;
      })
      .join("");

    $("#deadline").textContent = B.rsvpDeadline
      ? t("rsvp_deadline").replace("{d}", fmt(new Date(B.rsvpDeadline), { day: "numeric", month: "long" }))
      : "";

    $("#regalo").hidden = !B.iban;
    $("#iban").textContent = B.iban;
    $("#iban-holder").textContent = B.ibanHolder;

    for (const [id, url, key] of [["#album", B.albumUrl, "photos_cta"], ["#playlist", B.playlistUrl, "music_cta"]]) {
      const el = $(id);
      el.classList.toggle("off", !url);
      url ? (el.href = url) : el.removeAttribute("href");
      el.textContent = url ? `${t(key)} →` : t("soon");
    }

    renderRsvp();
    observe();
  }

  function guestNode(g, i, c = {}) {
    const node = $("#guest-tpl").content.firstElementChild.cloneNode(true);
    $$("[data-i18n]", node).forEach((el) => (el.textContent = t(el.dataset.i18n)));
    $$("[data-i18n-ph]", node).forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
    node.dataset.row = g.row ?? "";
    $(".g-name", node).value = c.name ?? g.name ?? "";
    $(".g-name", node).placeholder = t("p_name");
    $(".g-menu", node).value = c.menu ?? (["Adulto", "Niño", "Bebé"].includes(g.menu) ? g.menu : "Adulto");
    $(".g-allergies", node).value = c.allergies ?? g.allergies ?? "";
    const att = c.attending ?? (g.status === "No viene" ? "no" : "yes");
    $$("input[type=radio]", node).forEach((r) => {
      r.name = `att_${i}`;
      r.checked = r.value === att;
    });
    return node;
  }

  function renderRsvp() {
    const finder = $("#finder");
    const form = $("#rsvp-form");
    const intro = $("#rsvp-intro");
    const note = $("#rsvp-note");
    const box = $("#party");

    finder.hidden = partyState === "ok" || partyState === "loading";
    form.hidden = !finder.hidden;
    $("#rsvp-title").textContent = t("rsvp_title");
    note.hidden = true;

    if (partyState === "loading") {
      form.hidden = false;
      form.classList.add("busy");
      intro.textContent = t("rsvp_loading");
      box.innerHTML = "";
      $$("#rsvp-form > :not(.lead)").forEach((el) => el.classList.add("is-hidden"));
      return;
    }
    form.classList.remove("busy");
    $$("#rsvp-form .is-hidden").forEach((el) => el.classList.remove("is-hidden"));

    if (partyState !== "ok") {
      renderMatches();
      return;
    }

    const first = party.guests.map((g) => g.name.split(" ")[0]).filter(Boolean);
    $("#rsvp-title").textContent = t("rsvp_hello").replace("{names}", listJoin(first));
    intro.textContent = t(party.guests.length > 1 ? "rsvp_intro" : "rsvp_intro_one");

    // keep what the guest has typed when the language changes
    const current = readGuests();
    box.innerHTML = "";
    party.guests.forEach((g, i) => box.appendChild(guestNode(g, i, current[i])));

    // +1: only for invitations that have it enabled in the sheet
    const po = party.options?.plusOne;
    $("#plus-one").hidden = !po;
    if (po) {
      const prev = readPlusOne();
      const slot = $("#po-slot");
      slot.innerHTML = "";
      const n = guestNode({ name: "" }, "po", prev || {});
      n.classList.add("po");
      $(".seg", n).remove(); // the checkbox already says whether they come
      $(".g-name", n).placeholder = t("po_name");
      slot.appendChild(n);
    }

    $("#bus-field").hidden = party.options?.bus === false;

    if (party.replied) {
      note.hidden = false;
      note.textContent = t("f_already").replace("{d}", fmt(new Date(party.replied), { day: "numeric", month: "long" }));
      $("#send").textContent = t("f_update");
    }
    syncVisibility();
  }

  function renderMatches() {
    const list = $("#matches");
    const msg = $("#find-msg");
    list.innerHTML = matches
      .map((m, i) => `<li><button type="button" data-i="${i}"><strong>${esc(m.name)}</strong><span>${esc(t("its_me"))} →</span></button></li>`)
      .join("");
    msg.innerHTML =
      partyState === "bad"
        ? esc(t("rsvp_badlink"))
        : findState === "searching"
        ? esc(t("find_searching"))
        : findState === "many"
        ? esc(t("find_many"))
        : findState === "none"
        ? `${esc(t("find_none"))} <a href="mailto:${esc(B.contactEmail)}">${esc(B.contactEmail)}</a>`
        : findState === "error"
        ? esc(t("f_error"))
        : "";
  }

  function readGuests() {
    return $$("#party .guest").map((n) => ({
      row: +n.dataset.row,
      name: $(".g-name", n).value.trim(),
      attending: ($("input[type=radio]:checked", n) || {}).value || "yes",
      menu: $(".g-menu", n).value,
      allergies: $(".g-allergies", n).value.trim(),
    }));
  }

  function readPlusOne() {
    const n = $("#po-slot .guest");
    if (!n) return null;
    return { name: $(".g-name", n).value.trim(), menu: $(".g-menu", n).value, allergies: $(".g-allergies", n).value.trim() };
  }

  function syncVisibility() {
    const form = $("#rsvp-form");
    $$("#party .guest").forEach((n) => {
      const yes = ($("input[type=radio]:checked", n) || {}).value !== "no";
      n.classList.toggle("declined", !yes);
    });
    const anyYes = readGuests().some((g) => g.attending === "yes");
    const poOn = anyYes && $("#po-on").checked;
    $("#po-slot").hidden = !poOn;
    $("#plus-one").classList.toggle("off", !anyYes);
    $(".if-any-yes", form).hidden = !anyYes;
  }

  let io;
  function observe() {
    io ??= new IntersectionObserver(
      (es) => es.forEach((e) => e.isIntersecting && (e.target.classList.add("in"), io.unobserve(e.target))),
      { threshold: 0.12 }
    );
    $$(".reveal:not(.in)").forEach((el) => io.observe(el));
  }

  // ---------- data ----------
  // Without rsvpEndpoint the site runs in demo mode with two made-up invitations.
  const DEMO = [
    { key: "demo1", invitation: "DEMO-1", options: { plusOne: true, bus: true }, guests: [{ row: 1, name: "Invitada Prueba", menu: "Adulto" }] },
    {
      key: "demo2",
      invitation: "DEMO-2",
      options: { plusOne: false, bus: false },
      guests: [
        { row: 2, name: "Familia Prueba", menu: "Adulto" },
        { row: 3, name: "Pareja Prueba", menu: "Adulto" },
        { row: 4, name: "Peque Prueba", menu: "Niño" },
      ],
    },
  ];
  const norm = (s) => String(s || "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9 ]/g, " ").trim();

  async function api(params) {
    if (!B.rsvpEndpoint) {
      if (params.q != null) {
        const words = norm(params.q).split(/\s+/);
        const results = [];
        DEMO.forEach((inv) =>
          inv.guests.forEach((g) => {
            const w = norm(g.name).split(/\s+/);
            if (words.every((q) => w.some((x) => x.startsWith(q)))) results.push({ name: g.name, key: inv.key });
          })
        );
        return { ok: true, results };
      }
      const inv = DEMO.find((d) => d.key === params.i);
      return inv ? { ok: true, ...inv } : { ok: false };
    }
    const res = await fetch(`${B.rsvpEndpoint}?${new URLSearchParams(params)}`);
    return res.json();
  }

  async function loadParty() {
    partyState = "loading";
    renderRsvp();
    try {
      const data = await api({ i: key });
      if (!data.ok || !data.guests?.length) throw new Error("not found");
      party = data;
      partyState = "ok";
      const f = $("#rsvp-form");
      f.reset();
      $("#send").textContent = t("f_send");
      $("#status").textContent = "";
      if (data.bus) f.bus.value = data.bus;
      for (const k of ["song", "contact", "message"]) if (data[k]) f[k].value = data[k];
      $("#party").innerHTML = "";
      $("#po-slot").innerHTML = "";
    } catch {
      partyState = "bad";
      party = null;
      try {
        localStorage.removeItem("rsvp_i");
      } catch {}
    }
    renderRsvp();
  }

  let matches = [];
  let findState = ""; // "" | searching | many | none | error
  let findTimer, findSeq = 0;
  async function find(q) {
    const seq = ++findSeq;
    if (norm(q).replace(/\s/g, "").length < 3) {
      matches = [];
      findState = "";
      return renderMatches();
    }
    findState = "searching";
    renderMatches();
    try {
      const data = await api({ q });
      if (seq !== findSeq) return;
      matches = data.results || [];
      findState = data.tooMany ? "many" : matches.length ? "" : "none";
    } catch {
      if (seq !== findSeq) return;
      matches = [];
      findState = "error";
    }
    renderMatches();
  }

  // ---------- interactions ----------
  $("#lang").addEventListener("click", () => {
    lang = lang === "es" ? "en" : "es";
    try {
      localStorage.setItem("lang", lang);
    } catch {}
    render();
  });

  $("#find-q").addEventListener("input", (e) => {
    if (partyState === "bad") partyState = "find";
    clearTimeout(findTimer);
    findTimer = setTimeout(() => find(e.target.value), 300);
  });
  $("#matches").addEventListener("click", (e) => {
    const btn = e.target.closest("button[data-i]");
    if (!btn) return;
    key = matches[+btn.dataset.i].key;
    try {
      localStorage.setItem("rsvp_i", key);
    } catch {}
    loadParty();
  });
  $("#not-me").addEventListener("click", () => {
    key = "";
    party = null;
    partyState = "find";
    matches = [];
    findState = "";
    $("#find-q").value = "";
    try {
      localStorage.removeItem("rsvp_i");
    } catch {}
    if (params.has("i")) history.replaceState(null, "", location.pathname + location.hash);
    renderRsvp();
    $("#find-q").focus();
  });

  const form = $("#rsvp-form");
  const status = $("#status");
  form.addEventListener("input", syncVisibility);
  form.addEventListener("change", syncVisibility);

  form.addEventListener("submit", async (e) => {
    e.preventDefault();
    if (partyState !== "ok") return;
    status.className = "status";
    const guests = readGuests();
    const declinedAll = guests.every((g) => g.attending === "no");
    let plusOne = null;
    if (party.options?.plusOne && !declinedAll && $("#po-on").checked) {
      plusOne = readPlusOne();
      if (!plusOne.name) {
        $("#po-slot .g-name").focus();
        status.className = "status err";
        status.textContent = t("po_need_name");
        return;
      }
    }
    const payload = {
      i: key,
      lang,
      guests,
      plusOne,
      bus: declinedAll || party.options?.bus === false ? "none" : form.bus.value,
      song: form.song.value.trim(),
      contact: form.contact.value.trim(),
      message: form.message.value.trim(),
    };

    if (!B.rsvpEndpoint) {
      status.textContent = t("f_demo");
      console.log("RSVP payload (demo)", payload);
      return;
    }
    const btn = $("#send");
    btn.disabled = true;
    btn.textContent = t("f_sending");
    try {
      // text/plain avoids a CORS preflight, which Apps Script can't answer
      const res = await fetch(B.rsvpEndpoint, { method: "POST", headers: { "Content-Type": "text/plain;charset=utf-8" }, body: JSON.stringify(payload) });
      const data = await res.json();
      if (!data.ok) throw new Error(data.error || "error");
      status.textContent = t(declinedAll ? "f_sorry" : "f_thanks");
      status.classList.add("ok");
      party.replied = new Date().toISOString();
      // a +1 that has been saved becomes a normal guest of the invitation
      if (data.guests) {
        party.guests = data.guests;
        party.options = data.options || party.options;
        $("#po-on").checked = false;
        $("#party").innerHTML = "";
        $("#po-slot").innerHTML = "";
        renderRsvp();
        status.textContent = t(declinedAll ? "f_sorry" : "f_thanks");
        status.className = "status ok";
      }
    } catch {
      status.className = "status err";
      status.textContent = t("f_error");
    }
    btn.disabled = false;
    btn.textContent = t(party.replied ? "f_update" : "f_send");
  });

  $("#copy").addEventListener("click", async (e) => {
    try {
      await navigator.clipboard.writeText(B.iban.replace(/\s/g, ""));
      e.target.textContent = t("copied");
      setTimeout(() => (e.target.textContent = t("copy")), 1600);
    } catch {}
  });

  render();
  if (partyState === "loading") loadParty();
})();
